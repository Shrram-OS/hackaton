"""Базова модель: два прилади, жодного навчання.

Навіщо вона. По-перше, це перевірка роботоздатності: якщо вона проганяється
від початку до кінця й дає осмислені числа, то працює весь ланцюг — обгортка,
протокол, канали, правило тривоги. По-друге, це підлога для порівняння: будь-
яка навчена модель, яка не б'є цю, не вивчила нічого, чого не видно з
підручника.

Рішенням задачі вона не є: тут немає ні історії, довшої за згладжування, ні
кореляцій між каналами, ні власне навчання.

## Що вона дивиться

**Замкнена мода** — сідлова петля `mag_saddle_lm`. Це не причина зриву, а
його прояв: мода росте вже після того, як розряд перетнув межу. Сигнал
пізній — видно за останні сто мілісекунд, — зате майже без фону. Головний
внесок.

**Частка гринвальдівської межі.** Готової в даних немає, її треба скласти:
лінійний інтеграл з інтерферометра поділити на довжину хорди, струм узяти з
поясу Роговського, межу порахувати з геометрії машини. Сигнал слабший, зате
повільний: він дає запас часу там, де мода ще мовчить.

## Чого вона НЕ дивиться, хоч спершу здавалося, що варто

Частка випромінювання — сума болометричних хорд, поділена на введену
потужність. У сирому вигляді вона виглядає переконливо: за сто мілісекунд до
гасіння p95 = 10.9 проти 1.2 на тихих розрядах. Але тривога — подія на
розряд, тож порівнювати треба не миттєві значення, а **максимум за розряд**:

| максимум згладженого за розряд | тихі | зривні |
|---|---|---|
| `rad_frac`      | 1.17 | 0.92 |
| `f_gw`          | 0.67 | 0.68 |
| `mag_saddle_lm` | 0.007 | 0.021 |

За цим числом тихі розряди світяться **сильніше** за зривні. Болометр ловить
звичайне крайове випромінювання, яке трапляється й на спокійному розряді, а
зриви в цьому наборі здебільшого йдуть не радіаційним шляхом. Канал прибрано:
з ним модель давала нуль спійманих під бюджетом 5 % хибних.

Це головна пастка цієї задачі. Сигнал, який явно відрізняється перед зривом,
може бути марним для правила «одна тривога на розряд» — бо до того ж рівня
доходять і розряди, які нікуди не діваються.

## Звідки взялися пороги

Зміряно на 60 розрядах із сідом 777 (`toksym gen --shots 60 --seed 777`), на
ділянці плато струму. Пороги взято вище за максимум тихих розрядів, а не з
того, що дає кращий TPR: 0.014 для моди й 0.87 для частки межі — це найвищі
значення, яких у вибірці досягав розряд, що не зірвався.

Підбору під результат немає. Якщо вам треба краще — це і є ваша робота.

## Чого від неї очікувати

200 розрядів, запас 30 мс, бюджет хибних тривог 5 %. Пороги мірялися лише на
сіді 777; решту модель бачить уперше:

| сід      | спіймано вчасно | хибних | медіанне випередження |
|----------|-----------------|--------|-----------------------|
| 1        | 41 з 58 (71 %)  | 4.9 %  | 0.07 с                |
| 777      | 35 з 58 (60 %)  | 4.6 %  | 0.25 с                |
| 20261001 | 35 з 53 (66 %)  | 4.6 %  | 0.37 с                |

⚠️ **Міряйте на двох сотнях розрядів, не на тридцяти.** Та сама модель на
60–100 розрядах давала від 0.15 до 0.67 у цій самій клітинці. Це не
нестабільність моделі, а похибка вимірювання: на ста розрядах зараховується
лише два десятки зривів, а бюджет 5 % від шістнадцяти тихих — це рівно нуль
дозволених хибних тривог, тож поріг стрибає на одиницю й не ловить нічого.
На двохстах розрядах розкид падає з ±25 пунктів до ±5.

Друге, що видно з таблиці: **шістнадцять-дев'ятнадцять пізніх тривог** на
кожен прогін. Модель бачить ці зриви, але сигнал приходить уже всередині
вікна. Це пряма вада опори на сідлову петлю: мода росте після того, як
розряд перетнув межу. Хто хоче більший запас часу — мусить знайти, що саме
передує самій моді.

## Запуск

    toksym score --shots 200 --seed 1 --lead 0.1 -- python3 model_baseline.py

Залежностей немає — тільки стандартна бібліотека.
"""
import math
import sys
from pathlib import Path

# ── Геометрія машини. Відома й опублікована, вгадувати нічого. ──
A_MINOR = 0.95                       # малий радіус, м
KAPPA = 1.70                         # витягнутість
CHORD_M = 2.0 * A_MINOR * KAPPA      # довжина центральної хорди, м
GREENWALD_AREA = math.pi * A_MINOR ** 2

# ── Рівні, зміряні на тихих розрядах (див. докстрінг). ──
LM_WARN = 0.016       # максимум тихих 0.014, медіана зривних 0.021
F_GW_WARN = 0.95      # максимум тихих 0.87; беремо з запасом у хвіст

# М'якість сигмоїд. Різкіше — більше смикання на шумі, м'якше — пізніше.
LM_SOFT = 0.005
F_GW_SOFT = 0.08

# Згладжування. Крок 5 мс, тож стала часу ≈ 5 мс / alpha.
A_FAST = 0.10         # ≈ 50 мс: мода росте швидко, чекати не можна
A_SLOW = 0.02         # ≈ 250 мс: густина повзе, зате інтерферометр шумить

# Нижче цього струму розряд ще не вийшов на плато: там усі відношення
# безглузді, а ділення на малий струм дає викиди.
IP_MIN_MA = 1.0


def sigmoid(x, x0, soft):
    """Плавний перехід 0 → 1 навколо x0. Різкий поріг давав би смикання."""
    return 1.0 / (1.0 + math.exp(-(x - x0) / soft))


class Model:
    def start_shot(self, meta):
        # Стан скидається на кожен розряд: нести згладжене значення з
        # попереднього — це підглядати в чуже минуле.
        self.lm = 0.0
        self.f_gw = 0.0
        self.seen = False
        self.peak = 0.0

    def predict(self, t, channels):
        ip = channels.get("mag_ip_MA")
        chord = channels.get("ifr_chord_core")

        # Прилад має право відмовити — у каналі буде nan. Тоді тримаємо
        # попередню оцінку, а не вважаємо, що величина впала до нуля.
        if not _ok(ip) or not _ok(chord) or ip < IP_MIN_MA:
            return self.peak

        f_gw = (chord / CHORD_M) * GREENWALD_AREA / max(ip, 1e-6)

        # Модуль: сідловій петлі байдуже, у який бік повернулася мода.
        lm_raw = channels.get("mag_saddle_lm")
        lm = abs(lm_raw) if _ok(lm_raw) else self.lm

        if not self.seen:
            self.f_gw, self.lm = f_gw, lm
            self.seen = True
        else:
            self.f_gw += A_SLOW * (f_gw - self.f_gw)
            self.lm += A_FAST * (lm - self.lm)

        # Два незалежні шляхи до тривоги. Складаємо як «жоден не спрацював»:
        # сума переоцінювала б збіг двох слабких сигналів, максимум — навпаки,
        # ігнорував би його зовсім.
        a = sigmoid(self.lm, LM_WARN, LM_SOFT)
        b = sigmoid(self.f_gw, F_GW_WARN, F_GW_SOFT)
        p = 1.0 - (1.0 - a) * (1.0 - b)

        # Тривога — подія, а не стан: якщо розряд уже підходив до межі, це
        # сталося. Правило заліку бере найперший перетин порога, тож тримати
        # максимум чесніше за миттєве значення.
        self.peak = max(self.peak, p)
        return self.peak


def _ok(v):
    """Чи це справжнє число. nan означає відмову приладу на цьому кроці."""
    return v is not None and v == v


if __name__ == "__main__":
    # Запуск на заліку: toksym score --shots 200 --seed 1 -- python3 model_baseline.py
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from toksym_model import serve

    serve(Model())
